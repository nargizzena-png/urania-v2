<script>
// Butonul "Cere ofertă" din card preselectează formatul în formular
document.querySelectorAll('.pr-cta').forEach(function (btn) {
    btn.addEventListener('click', function (e) {
        e.preventDefault();
        var sel = document.getElementById('subject');
        if (sel) sel.value = btn.dataset.subject;
        document.getElementById('cerere').scrollIntoView({ behavior: 'smooth', block: 'start' });
    });
});
// Data în format românesc zz.ll.aaaa — punctele se pun automat
(function () {
    var d = document.getElementById('event_date');
    if (!d) return;
    d.addEventListener('input', function () {
        var v = d.value.replace(/\D/g, '').slice(0, 8);
        if (v.length > 4) v = v.slice(0, 2) + '.' + v.slice(2, 4) + '.' + v.slice(4);
        else if (v.length > 2) v = v.slice(0, 2) + '.' + v.slice(2);
        d.value = v;
    });
})();
</script>

